#!/bin/bash

# 1. تفعيل البيئة الافتراضية (استخدم المسار الكامل إذا واجهت مشكلة)
source venv/bin/activate

# 2. الانتظار لمدة 5 ثوانٍ (تأكد من وجود المسافة)
echo "جاري تشغيل السيرفر بعد 5 ثوانٍ..."
sleep 5

# 3. تشغيل السيرفر باستخدام اليوفيكورن
# نصيحة: استخدم python -m uvicorn للتأكد من استخدام مكتبات venv
python3 -m uvicorn app.main:app --reload
